class TranslationManager {
    constructor() {
        this.currentLang = localStorage.getItem('stroopLang') || this.getBrowserLanguage();
        this.applyTranslations();
    }

    getBrowserLanguage() {
        const browserLang = navigator.language || navigator.userLanguage;
        if (translations[browserLang]) {
            return browserLang;
        }
        // Fallback para o prefixo (ex: pt-PT -> pt-BR se existir)
        const prefix = browserLang.split('-')[0];
        const match = Object.keys(translations).find(lang => lang.startsWith(prefix));
        return match || 'pt-BR';
    }

    setLanguage(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            localStorage.setItem('stroopLang', lang);
            this.applyTranslations();
            // Disparar evento para que outras partes do app saibam que mudou
            window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
            return true;
        }
        return false;
    }

    t(key) {
        const langData = translations[this.currentLang];
        // Retorna a tradução ou a chave se não encontrar
        return langData[key] || key;
    }

    applyTranslations() {
        document.documentElement.lang = this.currentLang;
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = this.t(key);
            if (element.tagName === 'INPUT' && element.type === 'placeholder') {
                element.placeholder = translation;
            } else {
                element.innerHTML = translation;
            }
        });
    }
}

// Inicializar globalmente
const i18n = new TranslationManager();
window.i18n = i18n; // Expor explicitamente para window

// Atalho global para usar t('key')
window.t = (key) => i18n.t(key);

// Garantir que as traduções sejam aplicadas quando o DOM estiver pronto
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => i18n.applyTranslations());
} else {
    // Se o DOM já estiver carregado (caso o script seja movido para o final do body algum dia)
    i18n.applyTranslations();
}
